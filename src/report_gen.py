"""Automated Markdown report generator."""
import os
import pandas as pd
from typing import Dict, Any

class ReportGenerator:
    def __init__(self, reports_dir: str = "reports"):
        self.reports_dir = reports_dir
        os.makedirs(self.reports_dir, exist_ok=True)

    def build_report(
        self,
        metrics: Dict[str, Any],
        summary_df: pd.DataFrame,
        corr_df: pd.DataFrame,
        figure_rel_path: str = "figures/market_analytics_dashboard.png"
    ) -> str:
        """Compile statistical tables and visual charts into financial_report.md."""
        report_file = os.path.join(self.reports_dir, "financial_report.md")

        content = f"""# Automated Foreign Exchange (Forex) Analysis Report
**Generated by:** Codomax Financial Data Pipeline  
**Dataset Time Window:** {metrics['start_date']} to {metrics['end_date']}  
**Trading Observations Analyzed:** {metrics['trading_days']} business days  

---

## 1. Executive Summary
- **Tracked Assets:** {", ".join(metrics['currencies_tracked'])} against base currency (EUR).
- **Strongest Performing Asset:** **{metrics['best_performer']}** with a net change of **{metrics['best_return']}%**.
- **Weakest Performing Asset:** **{metrics['worst_performer']}** with a net change of **{metrics['worst_return']}%**.
- **Highest Volatility Asset:** **{metrics['most_volatile']}** with an annualized volatility of **{metrics['max_volatility']}%**.

---

## 2. Statistical Performance Summary
The following metrics were calculated using Pandas and vectorized NumPy routines:

{summary_df.to_markdown()}

---

## 3. Pairwise Return Correlation Matrix
Correlation coefficients reflecting how asset price movements co-vary:

{corr_df.to_markdown()}

---

## 4. Visual Analytics Dashboard
Below is the auto-generated analytical figure displaying exchange rate moving averages, return densities, correlation heatmaps, and outlier dispersions:

![Financial Analytics Dashboard]({figure_rel_path})

---

*Report automatically generated by Python Data & APIs Analysis Pipeline.*
"""
        with open(report_file, "w", encoding="utf-8") as f:
            f.write(content)

        print(f"[Report] Final report successfully generated at: {report_file}")
        return report_file
